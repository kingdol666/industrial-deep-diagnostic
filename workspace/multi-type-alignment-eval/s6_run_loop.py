#!/usr/bin/env python
"""s6_run_loop.py — headless S6 closed-loop campaign against the real
industrial-optimizer-loop CLI (init -> design -> ingest*N -> converge).

Truth (the "line"): dev_pos07(x) = 0.25 * (die_bolt_T3_pct - 2.0)^2 + N(0, 0.03)
— the S3 stripe amplitude as a function of the T3 die-bolt offset; minimum ~0
at x = 2.0 ("minimize -> 0"). Trial results are generated by this truth
function (the AWS/人工 stand-in), 3 replicates per trial.
"""
import json
import subprocess
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
PY = REPO / ".claude" / "shared" / "scripts" / ".venv" / "Scripts" / "python.exe"
OPT = REPO / ".claude" / "skills" / "industrial-optimizer-loop" / "scripts" / "optimizer.py"
RUN_DIR = HERE / "S6" / "run"
METRIC = "dev_pos07"
SIGMA = 0.03
X_STAR = 2.0


def truth(x):
    return 0.25 * (x - X_STAR) ** 2


def cli(*args, check=True):
    r = subprocess.run([str(PY), str(OPT), *args], capture_output=True,
                       text=True, timeout=600, shell=False)
    print(f"[opt {' '.join(args)}] rc={r.returncode}")
    if r.stdout.strip():
        print(r.stdout.strip()[-500:])
    if r.returncode != 0 and r.stderr.strip():
        print(r.stderr.strip()[-500:])
    if check and r.returncode != 0:
        raise SystemExit(f"optimizer {args} failed")
    return r


def read(rel):
    return json.loads((RUN_DIR / rel).read_text(encoding="utf-8"))


def main():
    rng = np.random.default_rng(20261001)
    cli("init", "--run-dir", str(RUN_DIR))
    obj = read("00_input/objective.json")
    max_rounds = obj["budget"]["max_rounds"]
    phase = "initialized"
    for i in range(1, max_rounds + 1):
        rid = f"R{i:03d}"
        cli("design", "--run-dir", str(RUN_DIR))
        design = read(f"02_rounds/{rid}/trial_design.json")
        trials_out = []
        for t in design["trials"]:
            sp = t["setpoints"]["die_bolt_T3_pct"]
            reps = t.get("replicates") or 1
            meas = {METRIC: [round(float(truth(sp) + rng.normal(0, SIGMA)), 4)
                             for _ in range(reps)]}
            trials_out.append({"trial_id": t["trial_id"], "status": "completed",
                               "measurements": meas})
        result = {"result_version": "1.0", "campaign_id": obj["campaign_id"],
                  "round_id": rid, "trials": trials_out}
        (RUN_DIR / "02_rounds" / rid / "trial_result.json").write_text(
            json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")
        cli("ingest", "--run-dir", str(RUN_DIR))
        phase = read("01_state/optimizer_state.json")["phase"]
        best = read("01_state/optimizer_state.json").get("incumbent", {})
        print(f"  -> phase={phase} round={rid}")
        if phase in ("converged", "paused", "exhausted", "aborted"):
            break
    print("terminal phase:", phase)
    if phase == "converged":
        cli("converge", "--run-dir", str(RUN_DIR))
    (HERE / "S6" / "terminal_phase.txt").write_text(phase, encoding="utf-8")


if __name__ == "__main__":
    main()
