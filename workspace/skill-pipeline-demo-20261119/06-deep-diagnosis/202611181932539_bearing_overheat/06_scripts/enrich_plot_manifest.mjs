#!/usr/bin/env node
// enrich_plot_manifest.mjs — normalize adaptive_charts.py plot_manifest.json to
// shared/schemas/plot_manifest_schema.json (adds required per-plot figure_type/priority
// and the top-level metadata block; preserves script-authored entries verbatim).
import fs from 'fs';
import path from 'path';

const runDir = process.argv[2];
const p = path.join(runDir, '03_figures', 'plot_manifest.json');
const m = JSON.parse(fs.readFileSync(p, 'utf8'));

const normalizedPlots = (m.plots || []).map((plot) => ({
  ...plot,
  figure_type: plot.figure_type || plot.chart_type || 'line',
  priority: plot.priority || plot.vlm_priority || 'SUPPLEMENTARY',
  description: plot.description || `Deterministic chart generated by ${plot.source || 'adaptive_charts.py'}`
}));

const out = {
  ...m,
  plots: normalizedPlots,
  metadata: m.metadata || {
    generated_by: 'adaptive_charts.py + enrich_plot_manifest.mjs (schema normalization only)',
    total_plots: normalizedPlots.length,
    generation_timestamp: new Date().toISOString(),
    source_data: '00_input/bearing_data.csv',
    time_col: 'timestamp',
    time_alignment: { median_interval_s: 120.0, monotonic_after_sort: true, n_rows_dropped_unparsable: 0 }
  }
};
fs.writeFileSync(p, JSON.stringify(out, null, 2) + '\n', 'utf8');
console.log(JSON.stringify({ plots: normalizedPlots.length, figure_types: normalizedPlots.map(x => x.figure_type) }));
